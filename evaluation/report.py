"""Turn results into docs/evaluation_results.md. Every number comes from the run; nothing is typed by hand."""
from __future__ import annotations

from typing import Any


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def cell(v: dict[str, Any]) -> str:
    ci = v["ci95"]
    return f"{v['ok']}/{v['n']} = {pct(v['rate'])}" + ("" if ci is None else f" (95% CI {pct(ci[0])} to {pct(ci[1])})")


def render(summaries: dict[str, Any], perf: dict[str, Any] | None, worst: dict[str, Any] | None, first: dict[str, Any] | None) -> str:
    L: list[str] = ["# Evaluation results (generated)", "",
                    "Generated by `python -m evaluation run`. Do not edit by hand. Read `docs/phase13.md` first: these numbers come from a",
                    "small set written by the same author as the rules, so they are an **optimistic** estimate of real-world behavior.", ""]
    for s in ("all", "dev", "heldout"):
        x = summaries[s]
        L += [f"## Split: {s} ({x['n_cases']} cases)", "",
              f"* Bad cases handled correctly: {cell(x['recall_all_bad'])}",
              f"* Normal texts wrongly changed or blocked: {x['benign']['false_positives']}/{x['benign']['n']} = {pct(x['benign']['fpr'])}"
              f" (95% CI {pct(x['benign']['fpr_ci95'][0])} to {pct(x['benign']['fpr_ci95'][1])})",
              f"* Sensitive values still present in released text: {x['exposed_after_release']}",
              f"* What the system did with bad cases: {x['actions_on_bad']}", "",
              "| Category | Handled correctly |", "|---|---|"]
        L += [f"| {k} | {cell(v)} |" for k, v in x["recall_by_category"].items()]
        L += ["", "| Category / origin | Handled correctly |", "|---|---|"]
        L += [f"| {k} | {cell(v)} |" for k, v in x["recall_by_category_origin"].items()]
        L += [""]
    a = summaries["all"]
    L += ["## By technique (all cases)", "", "| Technique | Handled correctly |", "|---|---|"]
    L += [f"| {k} | {v['ok']}/{v['n']} |" for k, v in a["recall_by_technique"].items()]
    b = a["benign"]
    L += ["", "## Normal texts that were changed or blocked (all cases)", "",
          f"By kind of text: {b['false_positive_by_technique']}", "", f"By action: {b['false_positive_by_action']}", "",
          f"Normal texts by kind (for scale): {b['benign_by_technique']}", ""]
    if first is not None:
        L += ["## First measurement (before any rule change)", "",
              "| Split | Bad cases handled | Normal texts wrongly changed |", "|---|---|---|"]
        for s in ("all", "dev", "heldout"):
            x = first[s]
            L.append(f"| {s} | {cell(x['recall_all_bad'])} | {x['benign']['false_positives']}/{x['benign']['n']} |")
        L.append("")
    if perf:
        L += ["## Speed", "", f"Machine: {perf['machine']}. {perf['note']}.", "",
              "| Input size (chars) | p50 ms | p95 ms | p99 ms | max ms |", "|---|---|---|---|---|"]
        L += [f"| {r['chars']} | {r['p50_ms']} | {r['p95_ms']} | {r['p99_ms']} | {r['max_ms']} |"
              for r in perf["input_check_by_size"].values()]
        L.append("")
    if worst:
        L += ["## Inputs built to be slow (20,000 characters)", "", "| Input | max ms of 3 runs | Decision |", "|---|---|---|"]
        L += [f"| {k} | {v['max_ms']} | {v['action']} |" for k, v in worst.items()]
        L.append("")
    return "\n".join(L) + "\n"
